// spec-index.mjs — rebuilds the "Spec ID → AP file map" section at the end of
// iphi-flow/docs/specs/n8n-vibe/00-index.md from the requirement blocks in 01…10.
// A block is a "### <ID> — <title>" heading; its AP target comes from either a
// "- **AP target file(s):** …" bullet or a "| AP target | … |" table row inside the block.
// Usage: node spec-index.mjs [spec-dir]
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'

const DIR = process.argv[2] ?? '/root/projects/phi/iphi-flow/docs/specs/n8n-vibe'
const HEADING = '## Spec ID → AP file map'
const files = readdirSync(DIR).filter(f => /^(0[1-9]|10)-.*\.md$/.test(f)).sort()

const rows = []
const missing = []
for (const file of files) {
  const lines = readFileSync(join(DIR, file), 'utf8').split('\n')
  let current = null
  let collecting = false
  const flush = () => {
    collecting = false
    if (!current) return
    if (!current.target) missing.push(`${current.id} (${file})`)
    rows.push(current)
  }
  for (const line of lines) {
    const head = line.match(/^### ([A-Z]{3}-\d+) — (.+)$/)
    if (head) {
      flush()
      current = { id: head[1], title: head[2].trim(), file, target: '' }
      continue
    }
    if (!current) continue
    if (collecting) {
      const nested = line.match(/^\s{2,}- (.+)$/)
      if (nested) { current.target += ' ' + nested[1]; continue }
      collecting = false
    }
    if (current.target) continue
    if (/^\s*- \*\*AP target[^:]*:\*\*\s*$/.test(line)) { collecting = true; continue }
    const bullet = line.match(/^\s*- \*\*AP target[^:]*:\*\*\s*(.+)$/)
    const cell = line.match(/^\|\s*AP target[^|]*\|\s*(.+?)\s*\|\s*$/)
    const text = bullet?.[1] ?? cell?.[1]
    if (text) current.target = text
  }
  flush()
}

const shortPaths = (text) => {
  const paths = [...text.matchAll(/`([^`]+)`/g)].map(m => m[1]).filter(p => /[/.]/.test(p) && !/\s/.test(p))
  const unique = [...new Set(paths)]
  return unique.length ? unique.map(p => `\`${p}\``).join(', ') : text.replace(/\|/g, '/').slice(0, 160)
}

const table = [
  `${HEADING}`,
  '',
  `Generated by \`iphi-flow/tools/spec-index.mjs\` from the requirement blocks (${rows.length} requirements in ${files.length} files). Re-run it after any spec edit. Paths are relative to the AP fork; \`WEB\` = \`packages/web\`, \`BUILDER\` = \`WEB/src/app/builder\`.`,
  '',
  '| ID | Requirement | Spec file | AP target |',
  '|---|---|---|---|',
  ...rows.map(r => `| ${r.id} | ${r.title.replace(/\|/g, '/')} | \`${r.file}\` | ${shortPaths(r.target || '—')} |`),
  '',
  missing.length ? `Cross-cutting requirements with no AP target of their own (they constrain the targets of other IDs): ${missing.join(', ')}.` : 'Every requirement names an AP target.',
  '',
].join('\n')

const indexPath = join(DIR, '00-index.md')
const index = readFileSync(indexPath, 'utf8')
const at = index.indexOf(HEADING)
if (at < 0) throw new Error(`"${HEADING}" not found in 00-index.md`)
writeFileSync(indexPath, index.slice(0, at) + table)
console.log(`rows: ${rows.length}; without AP target: ${missing.length}${missing.length ? ' → ' + missing.join(', ') : ''}`)
